def detect_opening(uci_moves: List[str]) -> Optional[Tuple[str, str]]:
    """
    Match UCI move list against ECO table; return (eco_code, name) of the
    longest prefix match, or None if no match is found.
    """
    if not uci_moves:
        return None

    moves_str = " ".join(uci_moves)
    best_match: Optional[Tuple[str, str]] = None
    best_len = 0

    for entry_moves, eco, name in _ECO_TABLE:
        if moves_str.startswith(entry_moves):
            n = len(entry_moves.split())
            if n > best_len:
                best_len = n
                best_match = (eco, name)

    return best_match
